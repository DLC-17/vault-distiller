import { App, Modal, Notice } from "obsidian";
import type LocalOrganizerPlugin from "./main";
import {
  resolveConflictPair,
  scanVaultForSyncConflicts,
} from "./sync-conflict-merger";
import { SyncConflictPair } from "./types";

interface ConflictItemState {
  pair: SyncConflictPair;
  selected: boolean;
}

/**
 * Interactive review and batch merge modal for Syncthing / Obsidian sync conflict files.
 */
export class SyncConflictModal extends Modal {
  plugin: LocalOrganizerPlugin;
  private items: ConflictItemState[] = [];
  private isRunning: boolean = false;
  private isCancelled: boolean = false;

  constructor(app: App, plugin: LocalOrganizerPlugin) {
    super(app);
    this.plugin = plugin;
  }

  onOpen(): void {
    this.scanAndRender();
  }

  onClose(): void {
    this.isCancelled = true;
    const { contentEl } = this;
    contentEl.empty();
  }

  private scanAndRender(): void {
    const { contentEl } = this;
    contentEl.empty();

    const pairs = scanVaultForSyncConflicts(this.app);
    this.items = pairs.map((pair) => ({ pair, selected: true }));

    contentEl.createEl("h2", { text: "Sync Conflict Resolver & Merger" });

    if (this.items.length === 0) {
      contentEl.createEl("p", {
        text: "✨ No sync conflict files found in your vault! Everything is in sync.",
        cls: "setting-item-description",
      });

      const closeContainer = contentEl.createDiv({ cls: "modal-button-container vd-modal-btn-row" });
      const closeBtn = closeContainer.createEl("button", { text: "Close", cls: "mod-cta" });
      closeBtn.onclick = () => this.close();
      return;
    }

    contentEl.createEl("p", {
      text: `Found ${this.items.length} sync conflict file(s) generated by Syncthing or cloud sync. Select the files you want to merge into their canonical counterparts:`,
      cls: "setting-item-description",
    });

    // Conflict list
    const listContainer = contentEl.createDiv({ cls: "vault-distiller-conflict-list vd-modal-list" });

    for (const item of this.items) {
      const card = listContainer.createDiv({ cls: "vault-distiller-conflict-card vd-modal-card" });

      // Top row: Checkbox + Conflict file path
      const topRow = card.createDiv({ cls: "vd-modal-row" });

      const cb = topRow.createEl("input", { type: "checkbox" });
      cb.checked = item.selected;
      cb.onchange = () => {
        item.selected = cb.checked;
        updateButtons();
      };

      topRow.createSpan({ text: item.pair.conflictFile.path, cls: "vd-modal-item-title" });

      // Target row
      const targetRow = card.createDiv({ cls: "vd-modal-subtext" });

      if (item.pair.canonicalFile) {
        if (item.pair.isOrphaned) {
          targetRow.setText(`↳ 🔄 Relocated target: [[${item.pair.canonicalFile.path}]]`);
        } else {
          targetRow.setText(`↳ 📝 Merges into: [[${item.pair.canonicalFile.path}]]`);
        }
      } else {
        targetRow.setText(`↳ 📁 Orphaned conflict: Will restore as "${item.pair.canonicalPath}"`);
      }
    }

    // Action button container
    const buttonRow = contentEl.createDiv({ cls: "modal-button-container vd-conflict-btn-row" });

    const leftGroup = buttonRow.createDiv();
    const selectAllBtn = leftGroup.createEl("button", { text: "Select All", cls: "vd-btn-margin-right" });
    selectAllBtn.onclick = () => {
      this.items.forEach((i) => (i.selected = true));
      this.scanAndRender();
    };

    const deselectBtn = leftGroup.createEl("button", { text: "Deselect All" });
    deselectBtn.onclick = () => {
      this.items.forEach((i) => (i.selected = false));
      this.scanAndRender();
    };

    const rightGroup = buttonRow.createDiv({ cls: "vd-btn-group" });

    const cancelBtn = rightGroup.createEl("button", { text: "Cancel" });
    cancelBtn.onclick = () => this.close();

    const mergeBtn = rightGroup.createEl("button", {
      text: "Merge & Clean Conflicts",
      cls: "mod-cta",
    });

    const updateButtons = () => {
      const selectedCount = this.items.filter((i) => i.selected).length;
      mergeBtn.disabled = selectedCount === 0;
      mergeBtn.setText(`Merge & Clean (${selectedCount})`);
    };
    updateButtons();

    mergeBtn.onclick = () => {
      const selected = this.items.filter((i) => i.selected).map((i) => i.pair);
      if (selected.length === 0) return;
      this.renderProgressView(selected);
    };
  }

  private renderProgressView(queue: SyncConflictPair[]): void {
    const { contentEl } = this;
    contentEl.empty();

    contentEl.createEl("h2", { text: "Merging Sync Conflicts" });

    const statusText = contentEl.createEl("p", {
      text: `Processing 0 of ${queue.length}...`,
      cls: "setting-item-description",
    });

    const progressBar = contentEl.createEl("progress", { cls: "vd-modal-progress" });
    progressBar.max = queue.length;
    progressBar.value = 0;

    const logContainer = contentEl.createDiv({ cls: "vault-distiller-log-container vd-modal-log" });

    const buttonRow = contentEl.createDiv({ cls: "modal-button-container vd-modal-btn-row" });

    const stopBtn = buttonRow.createEl("button", { text: "Stop" });
    stopBtn.onclick = () => {
      this.isCancelled = true;
      stopBtn.disabled = true;
      stopBtn.setText("Stopping...");
    };

    const appendLog = (msg: string) => {
      logContainer.createDiv({ text: msg, cls: "vd-modal-log-line" });
      logContainer.scrollTop = logContainer.scrollHeight;
    };

    void this.runQueue(queue, progressBar, statusText, appendLog, stopBtn);
  }

  private async runQueue(
    queue: SyncConflictPair[],
    progressBar: HTMLProgressElement,
    statusText: HTMLParagraphElement,
    appendLog: (msg: string) => void,
    stopBtn: HTMLButtonElement
  ): Promise<void> {
    this.isRunning = true;
    this.isCancelled = false;
    let successCount = 0;
    let failedCount = 0;

    for (let i = 0; i < queue.length; i++) {
      if (this.isCancelled) {
        appendLog("⏹️ Process stopped by user.");
        break;
      }

      const pair = queue[i];
      progressBar.value = i + 1;
      statusText.setText(`[${i + 1}/${queue.length}] Merging "${pair.conflictFile.name}"...`);
      appendLog(`▶ [${i + 1}/${queue.length}] Resolving: ${pair.conflictFile.path}`);

      try {
        const result = await resolveConflictPair(this.app, pair);
        successCount++;
        appendLog(`   ✅ ${result.message}`);
      } catch (err) {
        failedCount++;
        const msg = err instanceof Error ? err.message : String(err);
        appendLog(`   ❌ Error: ${msg}`);
      }
    }

    this.isRunning = false;
    statusText.setText(`Finished! Successfully resolved ${successCount} conflict(s). ${failedCount > 0 ? `(${failedCount} failed)` : ""}`);
    stopBtn.setText("Done");
    stopBtn.className = "mod-cta";
    stopBtn.disabled = false;
    stopBtn.onclick = () => this.close();
    new Notice(`Vault Distiller: Resolved ${successCount} sync conflict file(s).`);
  }
}
